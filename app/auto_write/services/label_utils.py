# 정규화 라벨 → 대표키(클러스터의 첫 원소)
CLUSTER_OF: dict[str, str] = {}
for _cluster in SYNONYMS:
    _rep = key(_cluster[0])
    for _alias in _cluster:
        CLUSTER_OF[key(_alias)] = _rep


def cluster_rep(norm_label: str) -> Optional[str]:
    """정규화 라벨이 속한 동의어 클러스터 대표키. 없으면 None."""
    return CLUSTER_OF.get(norm_label)


# --- Placeholder detection ---

_OBVIOUS_PATTERNS = (
    re.compile(r"^[○●\-\.\s]+$"),
    re.compile(r"^(http|https)://$"),
    re.compile(r"^[\d,.\s]+$"),
)


def is_obvious_placeholder(value: str) -> bool:
    """값이 명백한 placeholder(점선·공백·기호)인지 판별한다."""
    v = value.strip()
    if not v:
        return True
    for pat in _OBVIOUS_PATTERNS:
        if pat.match(v):
            return True
    if len(v) <= 2 and not any(c.isalnum() for c in v):
        return True
    return False
