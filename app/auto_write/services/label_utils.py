# --- 라벨 정규화 / 장식 제거 ---

_BULLET_PREFIX_RE = re.compile(r"^[○●◯◌▶▷◀◁◆◇■□▪▫▸▹◦‣⦁·∙•*※→⇒]+")
_NUM_PREFIX_RES = (
    re.compile(r"^\d{1,2}\s*[.)]\s*"),
    re.compile(r"^[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]\s*"),
    re.compile(r"^[가나다라마바사아자차카타파하]\s*[.)]\s*"),
    re.compile(r"^[ⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩ]\s*[.)]?\s*"),
)
HAS_WORD_RE = re.compile(r"[가-힣A-Za-z0-9]")
_HAS_WORD_RE = HAS_WORD_RE  # backward compat alias


def strip_label_decoration(key: str) -> str:
    """정규화 라벨 키에서 선행 글머리표/순번 접두를 보수적으로 제거한다."""
    s = key
    for _ in range(2):
        before = s
        s = _BULLET_PREFIX_RE.sub("", s, count=1)
        for rx in _NUM_PREFIX_RES:
            s2 = rx.sub("", s, count=1)
            if s2 != s:
                s = s2
                break
        if s == before:
            break
    s = s.strip()
    if not HAS_WORD_RE.search(s):
        return key
    return s


def key(text: str) -> str:
    """라벨 비교용 핵심 키: 괄호·공백 제거 + 선행 글머리표/순번 장식 제거."""
    return strip_label_decoration(SubmittableFiller._key(text))


